const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const window={markdownit:require('../dashboard/web/markdown-it.min.js')};
vm.runInNewContext(fs.readFileSync('dashboard/web/markdown.js','utf8'),{window,WeakMap});
const md=window.ConversationMarkdown;
const original='## Reply\n\n**Real Time** and [Android](https://example.org/path).\n\n- Use `git status`\n- Keep 🎸\n\n```sh\ngit status --short\n```';
const html=md.html(original);
assert.match(html,/<strong>Real Time<\/strong>/);
assert.match(html,/<a href="https:\/\/example.org\/path" target="_blank" rel="noopener noreferrer">Android<\/a>/);
assert.match(html,/<code>git status<\/code>/);assert.match(html,/<ul/);assert.match(html,/<pre/);
assert.match(html,/data-md-start=/);
assert(!md.html('<img src=x onerror=alert(1)>').includes('<img'));
assert(!md.html('[bad](javascript:alert(1))').includes('<a'));
assert(!md.html('[bad](data:text/html,evil)').includes('<a'));
assert(!md.html('[bad](java&#x73;cript:evil)').includes('<a'));
assert(!md.html('![image](https://example.org/tracker)').includes('<img'));
assert.match(md.html('```html\n<script>alert(1)</script>\n```'),/&lt;script&gt;/);
const body={textContent:'rendered text',classList:{add(){}}};md.render(body,original);
assert.equal(md.source(body),original);assert.equal(body.innerHTML,html);
assert.equal(md.source({textContent:'plain fallback'}),'plain fallback');
console.log('Markdown: standard blocks/inlines, label links, escaped HTML, rejected executable URLs, no external image fetch, canonical source retained.');
