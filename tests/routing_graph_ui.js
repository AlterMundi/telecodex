"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const context={window:{}};vm.createContext(context);vm.runInContext(fs.readFileSync("dashboard/web/routing_graph.js","utf8"),context);
const {Timeline,preview}=context.window.RoutingGraph;
const model=new Timeline();
const input={id:"first",text:"Original <script>literal</script>",phase:"accepted"};
model.input(input);assert.equal(model.nodes.size,2);
const target={chat_id:1,thread_id:7};
const route={instruction:"instruction-one",label:"Alpha",target,relation:{kind:"new"},requests:["request-one"],forwarded_original:input.text,transport_phase:"accepted",results:[]};
model.trace({...input,routes:[route]});
assert.equal(model.nodes.get("route:instruction-one").text,input.text);
assert.equal(model.nodes.get("route:instruction-one").index,2);
assert.equal(model.edges.size,2);
const firstResult={source:"delivery:one",phase:"presented",text_excerpt:"Original result",instruction_covered:true,declared:true,completed:true,current:true};
model.trace({...input,routes:[{...route,results:[firstResult]}]});
assert(model.edges.has(JSON.stringify(["route:instruction-one","delivery:one","incorporated"])));
const resultIndex=model.nodes.get("delivery:one").index;
model.input({id:"correction",text:"Use43 instead of41",phase:"accepted",voice:{}});
const correction={...route,instruction:"instruction-two",relation:{kind:"amends"},forwarded_original:"Use43 instead of41",results:[{...firstResult,instruction_covered:false,current:false}]};
model.trace({id:"correction",routes:[correction]});
assert.equal(model.nodes.get("route:instruction-two").title,"Correction → #Alpha");
assert(!model.edges.has(JSON.stringify(["route:instruction-two","delivery:one","incorporated"])));
assert.equal(model.nodes.get("delivery:one").index,resultIndex);
model.result({id:"native:unlinked",kind:"integrator_answer",preview:"Let me check both sessions"});
assert(![...model.edges.values()].some(edge=>edge.to==="native:unlinked"),"No fabricated nearest-prompt link");
const beforeLate=model.nodes.size;
model.trace({id:"correction",routes:[{...correction,results:[{...firstResult,source:"delivery:corrected",text_excerpt:"Updated473",instruction_covered:true}]}]});
assert.equal(model.nodes.get("delivery:corrected").index,beforeLate);
assert(model.edges.has(JSON.stringify(["route:instruction-two","delivery:corrected","incorporated"])));
const count=model.nodes.size,version=model.version;
model.trace({id:"correction",routes:[{...correction,results:[{...firstResult,source:"delivery:corrected",text_excerpt:"Updated473",instruction_covered:true}]}]});
assert.equal(model.nodes.size,count);assert.equal(model.version,version);
assert.equal(Array.from(preview("😀".repeat(301))).length,300);
model.trace({id:"correction",routes:[{...correction,instruction:"other-session",label:"Alpha",target:{chat_id:1,thread_id:8},results:[]}]});
assert.notEqual(model.nodes.get("route:instruction-two").lane,model.nodes.get("route:other-session").lane,"Same labels do not merge distinct sessions");
model.trace({id:"correction",routes:[{...correction,results:[{...firstResult,source:"delivery:undeclared",instruction_covered:true,declared:false}]}]});
assert(!model.edges.has(JSON.stringify(["route:instruction-two","delivery:undeclared","incorporated"])));
const discovery=new Timeline();
discovery.result({id:"delivery:found-later",label:"#Same",kind:"worker_result",preview:"A reply"});
discovery.input({id:"input-later",text:"Earlier input",phase:"accepted"});
discovery.trace({id:"input-later",routes:[{...route,results:[{...firstResult,source:"delivery:found-later"}]}]});
assert.equal(discovery.nodes.get("delivery:found-later").lane,discovery.nodes.get("route:instruction-one").lane);
assert(![...discovery.lanes.keys()].some(key=>key.startsWith("unlinked:")),"Resolved sources leave no duplicate placeholder lane");
model.reset();assert.equal(model.nodes.size,0);assert.equal(model.edges.size,0);
console.log("PASS routing timeline: exact text, voice/correction, late result, declared incorporation, stable identities, separate sessions, reset; no inferred input link or effects.");
