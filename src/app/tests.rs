#[cfg(unix)]
#[test]
fn artifact_snapshot_retains_actual_bytes_with_partial_failure_and_no_path_authority() {
    use serde_json::json;
    use sha2::{Digest, Sha256};
    use std::os::unix::fs::symlink;
    let (app, _db) = sample_app();
    let root = tempfile::tempdir().unwrap();
    let out = root.path().join("out");
    fs::create_dir(&out).unwrap();
    let anchored = artifact_outputs::anchor(&out).unwrap().unwrap();
    let key = SessionKey::new(100, Some(7));
    let s = app
        .shared
        .store
        .ensure_session(key, 100, &sample_defaults())
        .unwrap();
    app.shared
        .store
        .set_session_codex_thread(key, "artifact-native")
        .unwrap();
    let local = app
        .shared
        .store
        .record_turn_started(
            s.id,
            &TurnRequest {
                session_key: key,
                from_user_id: 100,
                prompt: "Make files".into(),
                runtime_instructions: None,
                attachments: vec![],
                review_mode: None,
                override_search_mode: None,
            },
        )
        .unwrap();
    app.shared
        .store
        .record_turn_native_thread(local, "artifact-native")
        .unwrap();
    app.shared
        .store
        .record_native_message(
            local,
            "artifact-native",
            "physical",
            "result",
            Some("final_answer"),
            "Output",
        )
        .unwrap();
    let bytes = b"Immutable generated bytes";
    fs::write(out.join("good.txt"), bytes).unwrap();
    let private = root.path().join("unrelated-private");
    fs::write(&private, b"Never copy this").unwrap();
    symlink(&private, out.join("bad.txt")).unwrap();
    let cfg = crate::interaction::ArtifactConfig {
        directory: root.path().join("retained"),
        retention_hours: 24,
        max_file_bytes: 1024,
        max_total_bytes: 4096,
    };
    let observed = json!({"native":"artifact-native","turn":"physical","item":"result"});
    let before = app
        .shared
        .store
        .interaction_presentation_list(100, key, 0, 0)
        .unwrap();
    assert!(
        artifact_outputs::snapshot(
            &app.shared,
            &cfg,
            local,
            100,
            &out,
            Some(&anchored),
            &observed
        )
        .is_err()
    );
    let artifacts = app.shared.store.artifact_list(100, key).unwrap();
    let after = app
        .shared
        .store
        .interaction_presentation_list(100, key, 0, 0)
        .unwrap();
    assert_eq!(
        before["items"][0]["revision"],
        after["items"][0]["revision"]
    );
    assert_eq!(after["items"][0]["artifacts"].as_array().unwrap().len(), 2);
    assert_eq!(artifacts["items"].as_array().unwrap().len(), 2);
    let id = artifacts["items"]
        .as_array()
        .unwrap()
        .iter()
        .find(|a| a["available"] == true)
        .unwrap()["id"]
        .as_str()
        .unwrap();
    let retained = app.shared.store.artifact_get(100, key, id).unwrap();
    assert_eq!(retained.sha256, format!("{:x}", Sha256::digest(bytes)));
    assert_eq!(
        fs::read(cfg.directory.join(&retained.sha256)).unwrap(),
        bytes
    );
    assert_eq!(
        app.shared.store.artifact_storage_bytes().unwrap(),
        bytes.len() as i64
    );
    fs::remove_file(out.join("bad.txt")).unwrap();
    artifact_outputs::snapshot(
        &app.shared,
        &cfg,
        local,
        100,
        &out,
        Some(&anchored),
        &observed,
    )
    .unwrap();
    assert_eq!(
        app.shared.store.artifact_list(100, key).unwrap()["items"]
            .as_array()
            .unwrap()
            .iter()
            .find(|a| a["available"] == true)
            .unwrap()["id"],
        id
    );
    assert_eq!(fs::read(&private).unwrap(), b"Never copy this");
    // New response snapshots enumerate their frozen names, not later live files.
    use std::os::unix::fs::MetadataExt;
    let meta = fs::metadata(out.join("good.txt")).unwrap();
    let mut frozen = observed.clone();
    frozen["files"] = json!({"good.txt":[meta.dev(),meta.ino(),meta.len(),meta.mtime(),meta.mtime_nsec(),meta.ctime(),meta.ctime_nsec()]});
    for index in 0..11 {
        fs::write(out.join(format!("later-{index}.txt")), b"Later response").unwrap();
    }
    artifact_outputs::snapshot(
        &app.shared,
        &cfg,
        local,
        100,
        &out,
        Some(&anchored),
        &frozen,
    )
    .unwrap();
    assert_eq!(
        app.shared.store.artifact_list(100, key).unwrap()["items"]
            .as_array()
            .unwrap()
            .len(),
        2
    );
    // A disappeared selected file is unavailable, never silently omitted.
    frozen["files"] = json!({"missing.txt":[]});
    assert!(
        artifact_outputs::snapshot(
            &app.shared,
            &cfg,
            local,
            100,
            &out,
            Some(&anchored),
            &frozen
        )
        .is_err()
    );
    assert!(
        app.shared.store.artifact_list(100, key).unwrap()["items"]
            .as_array()
            .unwrap()
            .iter()
            .any(|v| v["name"] == "missing.txt" && v["available"] == false)
    );
}

